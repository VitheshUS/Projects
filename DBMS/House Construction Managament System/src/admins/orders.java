    public void showall()
{
    int id=0;
        try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.orders";
            PreparedStatement pr=con.prepareStatement(query);
           
            ResultSet rs=pr.executeQuery();
            tb1=(DefaultTableModel)jTable1.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object[] o={rs.getString("oid"),rs.getString("name"),rs.getString("contact"),rs.getString("area"),rs.getString("bhk"),rs.getString("location"),rs.getString("floors")};
            tb1.addRow(o);
            }
            
        } catch (SQLException ex) {
            Logger.getLogger(orders.class.getName()).log(Level.SEVERE, null, ex);
        
        }
}

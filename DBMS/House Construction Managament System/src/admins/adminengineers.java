public void insert()
{
    String nme=name.getText();
    String cont=contact.getText();
    int sal=Integer.parseInt(salary.getText());
    try{
        Connection con=DBconnection.getconnnection();
        String query="insert into hcms.engineers(name,contact,salary) values(?,?,?)";
        PreparedStatement prt=con.prepareStatement(query);
        prt.setString(1, nme);
        prt.setString(2, cont);
        prt.setInt(3, sal);
        int count=prt.executeUpdate();
        if(count>0)
            JOptionPane.showMessageDialog(this, "Succesfull");
        else
            JOptionPane.showMessageDialog(this, "Succesfull");
    }   catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
}
public boolean duplicate()
{
     String nme=name.getText();
        Boolean isExist=false;
        try{
            Connection con=DBconnection.getconnnection();
            PreparedStatement prt=con.prepareStatement("select * from hcms.engineers where name=?");
            prt.setString(1, nme);
           ResultSet rs= prt.executeQuery();
           if(rs.next())
           {
               isExist=true;
               JOptionPane.showMessageDialog(this, "Acoount already Exist");
           }
          

        }catch(Exception e)
        {
            e.printStackTrace();
        }
        return isExist;
}

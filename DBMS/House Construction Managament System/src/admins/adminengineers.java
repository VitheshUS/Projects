    public void update()
{
   
    if(validation())
    { String eid=engid.getText();
    try {
            Connection con=DBconnection.getconnnection();
            String query="update hcms.engineers  set name=?,contact=?,salary=? where eid=?";
            PreparedStatement pr;
            pr = con.prepareStatement(query);
            pr.setString(1,name1.getText() );
            pr.setString(2, contact1.getText());
            pr.setString(3,  salary1.getText());
            pr.setString(4, eid);
            int rs=pr.executeUpdate();
            if(rs!=0)JOptionPane.showMessageDialog(this, "Successfully updated");
            else
            JOptionPane.showMessageDialog(this, "Unsuccessfully");
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
    
        }
    }
    else
    JOptionPane.showMessageDialog(this, "incorrect values");
    showall();  
}
    
    
    
    
    

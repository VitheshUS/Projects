    public void search(String st)
    {
      tb1=(DefaultTableModel)jTable1.getModel();
        TableRowSorter<DefaultTableModel> tr=new TableRowSorter<>(tb1);
        jTable1.setRowSorter(tr);
        tr.setRowFilter(RowFilter.regexFilter(st.toLowerCase()));
      
        
    }
    
    

    public void showall()
{
    try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.house order by hid";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
             tb1=(DefaultTableModel)jTable1.getModel();
            tb1.setRowCount(0);
            
            while(rs.next())
            {
                Object o[]={rs.getString("owner"),rs.getString("location"),rs.getString("area"),rs.getString("cost")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            Logger.getLogger(adminhomes.class.getName()).log(Level.SEVERE, null, ex);
        }
}

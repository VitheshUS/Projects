public void appendtobill()
{
    
    try {
            Connection con=DBconnection.getconnnection();
            String query2="select * from hcms.house where hid=?";
            PreparedStatement pr2=con.prepareStatement(query2);
            pr2.setInt(1,hid);
          ResultSet rs=pr2.executeQuery();
            rs.next();
            String name=rs.getString("owner");
            String contact=rs.getString("contact");
            String housename=rs.getString("housename");
            String location=rs.getString("location");
            String bhk=rs.getString("bhk");
            String area=rs.getString("area");
            
            
            Area.append("------------------------------------------------------------------------------------\n\n");
    Area.append("Name                                                       "+name+"\n");
    Area.append("Contact                                                    "+contact+"\n");
    Area.append("House Name                                           "+housename+"\n");
    Area.append("Location                                                  "+location+"\n");
    Area.append("BHK                                                          "+bhk+"\n");
    Area.append("Area                                                         "+area+"\n");
    
    
        } catch (SQLException ex) {
            Logger.getLogger(Generatebill.class.getName()).log(Level.SEVERE, null, ex);
        }
   
    
    
}

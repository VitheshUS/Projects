public void addadmin()
{
    String name=jTextField1.getText();
        String pass=jPasswordField1.getText();
        try{
            Connection con=DBconnection.getconnnection();
            String query="insert into hcms.admin(name,password) values(?,?)";
            PreparedStatement pr=con.prepareStatement(query);
            pr.setString(1, name);
            pr.setString(2, pass);
            int count=pr.executeUpdate();
            if(count>0)
            {
                JOptionPane.showMessageDialog(this, "Succesfull");
            }
            else{
                 JOptionPane.showMessageDialog(this, "Succesfull");
            }
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(this, "password length must be greater than 6");
        }
        
}
 public boolean validatesignup()
    {
        String user=jTextField1.getText();
        String pass=jPasswordField1.getText();
        
        if(user.equals("")||pass.equals(""))
        {
            JOptionPane.showMessageDialog(this, "Please enter the values correctly");
            return false;
        }
            return true;
        }
 public boolean duplicateuser()
    {
        String user=jTextField1.getText();
        Boolean isExist=false;
        try{
            Connection con=DBconnection.getconnnection();
            PreparedStatement prt=con.prepareStatement("select * from hcms.admin where name=?");
            prt.setString(1, user);
           ResultSet rs= prt.executeQuery();
           if(rs.next())
           {
               isExist=true;
               JOptionPane.showMessageDialog(this, "Acoount already Exist");
           }
          

        }catch(Exception e)
        {
            e.printStackTrace();
        }
        return isExist;
    }

    public boolean validation()
{
    if(workerid.getText().equals("")||name1.getText().equals("")||contact1.getText().equals("")
            ||salary1.getText().equals("")||spec1.getText().equals(""))
        return false;
        return true;
}





    public void update()
{
   
    if(validation())
    { String eid=workerid.getText();
    try {
            Connection con=DBconnection.getconnnection();
            String query="update hcms.workers  set name=?,contact=?,specialization=?,salary=? where wid=?";
            PreparedStatement pr;
            pr = con.prepareStatement(query);
            pr.setString(1,name1.getText() );
            pr.setString(2, contact1.getText());
            pr.setString(3, spec1.getText());
            pr.setString(4,  salary1.getText());
            pr.setString(5, eid);
            int rs=pr.executeUpdate();
            if(rs!=0)JOptionPane.showMessageDialog(this, "Successfully updated");
            else
            JOptionPane.showMessageDialog(this, "Unsuccessfully");
        } catch (SQLException ex) {
            Logger.getLogger(adminworkers.class.getName()).log(Level.SEVERE, null, ex);
    
        }
    }
    else
    JOptionPane.showMessageDialog(this, "incorrect values");
    showall();  
}
    
    
    
    
    

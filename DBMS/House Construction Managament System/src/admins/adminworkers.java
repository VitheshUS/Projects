    public void insert()
{
    String nme=name.getText();
    String cont=contact.getText();
    int sal=Integer.parseInt(salary.getText());
    String spec=specialization.getText();
   
    
    try{
        Connection con=DBconnection.getconnnection();
        String query="insert into hcms.workers(name,contact,salary,specialization) values(?,?,?,?)";
        PreparedStatement prt=con.prepareStatement(query);
        prt.setString(1, nme);
        prt.setString(2, cont);
        prt.setInt(3, sal);
        prt.setString(4, spec);
        
        int count=prt.executeUpdate();
        if(count>0)
            JOptionPane.showMessageDialog(this, "Succesfull");
        else
            JOptionPane.showMessageDialog(this, "Unuccesfull");
    }   catch (SQLException ex) {
            Logger.getLogger(adminworkers.class.getName()).log(Level.SEVERE, null, ex);
        }
}
    
    
    
    
    
public boolean duplicate()
{
     String nme=name.getText();
        Boolean isExist=false;
        try{
            Connection con=DBconnection.getconnnection();
            PreparedStatement prt=con.prepareStatement("select * from hcms.workers where name=?");
            prt.setString(1, nme);
           ResultSet rs= prt.executeQuery();
           if(rs.next())
           {
               isExist=true;
               JOptionPane.showMessageDialog(this, "Acoount already Exist");
               
           }
          

        }catch(Exception e)
        {
            e.printStackTrace();
        }
        return isExist;
}
public boolean valid()
{
             String nme=name.getText();
    String cont=contact.getText();
     String regexcont="^(\\+91[\\-\\s]?)?[0]?(91)?[6789]\\d{9}$";
    
    
    if(!(EmailValidation.patterncontact(cont, regexcont)))//validation of contact
        {
            System.out.println("Enter The phone number");
            JOptionPane.showMessageDialog(this, "Incorrect phone number");
            return false;
            
    }
    
    
        
    else if(nme.equals("")||cont.equals(""))
        {
            JOptionPane.showMessageDialog(this, "Please enter the values correctly");
            return false;
        }
            return true;
}
          

                                           

         

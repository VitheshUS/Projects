    public void showall()
    {
        try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.workers";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
            tb1=(DefaultTableModel)jTable1.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getInt("wid"),rs.getString("name"),rs.getString("contact"),rs.getInt("salary"),rs.getString("specialization")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            Logger.getLogger(adminworkers.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
    
    
    
    

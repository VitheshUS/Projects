public void showall()
{
    try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.clients";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
             tb1=(DefaultTableModel)jTable1.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getString("cid"),rs.getString("name"),rs.getString("contact"),rs.getString("emal")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            Logger.getLogger(Clients.class.getName()).log(Level.SEVERE, null, ex);
        }
}

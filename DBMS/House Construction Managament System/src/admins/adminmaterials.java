    public void displaykilos()
    {
        try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.kilogram";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
             tb1=(DefaultTableModel)tablekg.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getString("name"),rs.getString("quantity"),rs.getInt("cost")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

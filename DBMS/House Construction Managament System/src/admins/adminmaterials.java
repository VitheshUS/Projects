    ///////////////////////////////Search materials in storage///////////////////////////////////////////////////////
    
    public void searchkilo(String st)
    {
        tb1=(DefaultTableModel)tablekg.getModel();
        TableRowSorter<DefaultTableModel> tr=new TableRowSorter<>(tb1);
        tablekg.setRowSorter(tr);
        tr.setRowFilter(RowFilter.regexFilter(st));
        
        
        tb2=(DefaultTableModel)tableliters.getModel();
        TableRowSorter<DefaultTableModel> tr1=new TableRowSorter<>(tb2);
        tableliters.setRowSorter(tr1);
        tr1.setRowFilter(RowFilter.regexFilter(st));
        
        
        
        tb3=(DefaultTableModel)tableblocks.getModel();
        TableRowSorter<DefaultTableModel> tr2=new TableRowSorter<>(tb3);
        tableblocks.setRowSorter(tr2);
        tr2.setRowFilter(RowFilter.regexFilter(st));
        
        tb4=(DefaultTableModel)allmaterials.getModel();
        TableRowSorter<DefaultTableModel> tr3=new TableRowSorter<>(tb4);
        allmaterials.setRowSorter(tr3);
        tr3.setRowFilter(RowFilter.regexFilter(st));
    }

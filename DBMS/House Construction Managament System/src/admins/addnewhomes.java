    public void insertedintoselectedmaterials()
{
    String name=matl.getText();
    int id=Integer.parseInt(mid.getText());
    int count=Integer.parseInt(coun.getText());
    int cost=0;
    try{
            Connection con=DBconnection.getconnnection();
            String query="select cost from hcms.materials m join hcms.kilogram k where k.k_mid=m.mid and k.k_mid=?";
            PreparedStatement pr=con.prepareStatement(query);
            pr.setInt(1, id);
            ResultSet rs=pr.executeQuery();
            if(rs.next())
            {
               cost=rs.getInt("cost");
            }
             
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
    try{
            Connection con=DBconnection.getconnnection();
            String query="select cost from hcms.materials m join hcms.blocks b where b.b_mid=m.mid and b.b_mid=?";
            PreparedStatement pr=con.prepareStatement(query);
            pr.setInt(1, id);
            ResultSet rs=pr.executeQuery();
            if(rs.next())
            {
               cost=rs.getInt("cost");
            }
             
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
    
    try{
            Connection con=DBconnection.getconnnection();
            String query="select cost from hcms.materials m join hcms.litres l where l.l_mid=m.mid and l.l_mid=?";
            PreparedStatement pr=con.prepareStatement(query);
            pr.setInt(1, id);
            ResultSet rs=pr.executeQuery();
            if(rs.next())
            {
               cost=rs.getInt("cost");
            }
             
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
    
    
    cost*=count;
    if(duplicate())
    {
    try{
            Connection con=DBconnection.getconnnection();
            String query="insert into hcms.selectedmaterials(s_mid,name,cost,quantity) values(?,?,?,?)";
            PreparedStatement pr=con.prepareStatement(query);
            pr.setInt(1, id);
            pr.setString(2, name);
            pr.setInt(3,cost);
            pr.setInt(4, count);
            int rs=pr.executeUpdate();
            
            if(rs<=0) JOptionPane.showMessageDialog(this, "Unsuccesfull");
             
        } catch (SQLException ex) {
            //Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, ""+name+" is out stock");
        }
    
    }
    else{
        
        try{
        Connection con=DBconnection.getconnnection();
        String query="select cost,quantity from hcms.selectedmaterials where s_mid=?";
        PreparedStatement prt=con.prepareStatement(query);
        prt.setInt(1, id);
        
       ResultSet rs=prt.executeQuery();
        if(rs.next()){
              count+=rs.getInt("quantity");
              cost+=rs.getInt("cost");
        } 
    }   catch (SQLException ex) {
            java.util.logging.Logger.getLogger(addmaterials.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        }
          
        
        
        //********************************************************    UPDATE SELECTED MATERIALS  *********************************************************
        try{
            Connection con=DBconnection.getconnnection();
            String query="update hcms.selectedmaterials set cost=?,quantity=? where s_mid=?";
            PreparedStatement pr=con.prepareStatement(query);
            pr.setInt(1,cost);
            pr.setInt(2, count);
            pr.setInt(3, id);
            int rs=pr.executeUpdate();
            
            if(rs<=0) JOptionPane.showMessageDialog(this, "Unsuccesfull");
             
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    showall();
}
    
    
    
    
    
    

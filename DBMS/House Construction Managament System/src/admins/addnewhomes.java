    //********************************************************    VALIDATION   *********************************************************
    public boolean valid()
    {
        String name=oname.getText();
        String cont=ocontact.getText();
        String housename=hname.getText();
        String area=harea.getText();
        String floor=(hfloor.getText());
        String hbhk=bhk.getText();
        String loc=hlocation.getText();
        String Tdays=days.getText();
        String engin=enngineer1.getText();
        String em=mail.getText();
        
        String regexPattern = "^(.+)@(\\S+)$";
        String regexcont="^(\\+91[\\-\\s]?)?[0]?(91)?[789]\\d{9}$";
          if(name.equals("")|| housename.equals("") || loc.equals("") || engin.equals("") || cont.equals("") || area.equals("") || floor.equals("") ||hbhk.equals("") ||Tdays.equals("")){
        JOptionPane.showMessageDialog(this, "Please Enter All Values");
              return false;
          }
          else{
        if(!(EmailValidation.patternMatches(em, regexPattern)))//validation of email
        {
            System.out.println("Enter The Valid Email");
            JOptionPane.showMessageDialog(this, "Incorrect email");
            return false;
            
        }
        if(!(EmailValidation.patterncontact(cont, regexcont)))//validation of contact
        {
            System.out.println("Enter The phone number");
            JOptionPane.showMessageDialog(this, "Incorrect phone number");
            return false;
            
        }
          else return true;
        
          }
    }
    
    
    
    

    public void search(String st)
    {
        tb1=(DefaultTableModel)jTable1.getModel();
        TableRowSorter<DefaultTableModel> tr=new TableRowSorter<>(tb1);
        jTable1.setRowSorter(tr);
        tr.setRowFilter(RowFilter.regexFilter(st));
        
        
        tb2=(DefaultTableModel)jTable2.getModel();
        TableRowSorter<DefaultTableModel> tr1=new TableRowSorter<>(tb2);
        jTable2.setRowSorter(tr1);
        tr1.setRowFilter(RowFilter.regexFilter(st));
        
        
        
        tb3=(DefaultTableModel)jTable3.getModel();
        TableRowSorter<DefaultTableModel> tr2=new TableRowSorter<>(tb3);
        jTable3.setRowSorter(tr2);
        tr2.setRowFilter(RowFilter.regexFilter(st));
        
        
    }
    
    
    public void displaykilos()
    {
        try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.kilogram";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
             tb1=(DefaultTableModel)jTable3.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getString("name"),rs.getInt("cost")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            Logger.getLogger(materials.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

public boolean valid()
    {
        
        String name=jTextField3.getText();
    String contact=jTextField4.getText();
    String email=jTextField5.getText();
    String area=jTextField6.getText();
    String floors=jTextField7.getText();
    String bhk=jTextField8.getText();
    String location=jTextField9.getText();
    String hname=jTextField1.getText();
    
      
    
    
    
    String regexPattern = "^(.+)@(\\S+)$";
    String regexcont="^(\\+91[\\-\\s]?)?[0]?(91)?[6789]\\d{9}$";
        if(!(EmailValidation.patternMatches(email, regexPattern)))//validation of email
        {
            System.out.println("Enter The Valid Email");
            JOptionPane.showMessageDialog(this, "Incorrect email");
            return false;
            
        }
        if(!(EmailValidation.patterncontact(contact, regexcont)))//validation of contact
        {
            System.out.println("Enter The phone number");
            JOptionPane.showMessageDialog(this, "Incorrect phone number");
            return false;
            
        }
    
    
    
    
    
    
    
    
    
    
    
    
        if(name.equals("")|| contact.equals("") || email.equals("") || floors.equals("") || bhk.equals("") || location.equals("") || hname.equals("")){
        JOptionPane.showMessageDialog(this, "Please enter all values");
            return false;
        }
        else return true;
    }

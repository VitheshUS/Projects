public void showall()
{
    try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.house";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
             tb1=(DefaultTableModel)jTable1.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getString("housename"),rs.getInt("area"),rs.getInt("cost"),rs.getString("owner"),rs.getString("contact"),rs.getInt("hid")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            Logger.getLogger(adminengineers.class.getName()).log(Level.SEVERE, null, ex);
        }
}


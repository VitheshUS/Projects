    public void log()
    {
        String user=username.getText();
       String pass=password.getText();
       try{
       Connection con=DBconnection.getconnnection();
       String query="select *from hcms.admin where name=? and password=?";
       PreparedStatement pst=con.prepareStatement(query);
       pst.setString(1, user);
       pst.setString(2, pass);
       ResultSet rs=pst.executeQuery();
       admin a=new admin();
       if(rs.next())
       {
           setVisible(false);         
           a.setVisible(true);
           a.setName(user);
       }
       else{
           JOptionPane.showMessageDialog(this, "Please sign in first");
       }
       
       }
       catch(Exception e)
       {
           e.printStackTrace();
       }        
    }
    public boolean validatesignup()
    {
                String user=username.getText();
        String pass=password.getText();
        
        if(user.equals("")||pass.equals(""))
        {
            JOptionPane.showMessageDialog(this, "Please enter the values correctly");
            return false;
        }
            return true;
    }

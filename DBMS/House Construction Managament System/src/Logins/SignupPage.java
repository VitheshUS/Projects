    public void insertSign(){                   //input user
        String user=username.getText();
        String pass=password.getText();
        String em=email.getText();
        String cont=contact.getText();
        
        try{
            Connection con=DBconnection.getconnnection();
            String query="insert into hcms.users(name,password,email,contact) values(?,?,?,?)";
            PreparedStatement pst=con.prepareStatement(query);
            pst.setString(1, user);
            pst.setString(2, pass);
            pst.setString(3, em);
            pst.setString(4, cont);
            int count=pst.executeUpdate();
            if(count>0)
            {
                JOptionPane.showMessageDialog(this, "Succesfull");
            }
            else{
                JOptionPane.showMessageDialog(this, "Unsuccesfull");
            }
        }catch(Exception e)
        {
            JOptionPane.showMessageDialog(this, e);
        }
        

    }
    public boolean validatesignup()
    {
        String user=username.getText();
        String pass=password.getText();
        String em=email.getText();
        String cont=contact.getText();
        String regexPattern = "^(.+)@(\\S+)$";
        String regexcont="^(\\+91[\\-\\s]?)?[0]?(91)?[6789]\\d{9}$";
        if(!(EmailValidation.patternMatches(em, regexPattern)))//validation of email
        {
            System.out.println("Enter The Valid Email");
            JOptionPane.showMessageDialog(this, "Incorrect email");
            return false;
            
        }
        if(!(EmailValidation.patterncontact(cont, regexcont)))//validation of contact
        {
            System.out.println("Enter The phone number");
            JOptionPane.showMessageDialog(this, "Incorrect phone number");
            return false;
            
        }
        else if(user.equals("")||pass.equals("")||em.equals("")||cont.equals(""))
        {
            JOptionPane.showMessageDialog(this, "Please enter the values correctly");
            return false;
        }
        
            return true;
        }
    public boolean duplicateuser()
    {
        String user=username.getText();
        Boolean isExist=false;
        try{
            Connection con=DBconnection.getconnnection();
            PreparedStatement prt=con.prepareStatement("select * from hcms.users where name=?");
            prt.setString(1, user);
           ResultSet rs= prt.executeQuery();
           if(rs.next())
           {
               isExist=true;
               JOptionPane.showMessageDialog(this, "Acoount already Exist");
           }
          

        }catch(Exception e)
        {
            e.printStackTrace();
        }
        return isExist;
    }
    

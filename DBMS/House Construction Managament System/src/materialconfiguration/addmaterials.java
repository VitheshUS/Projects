    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        String name=nme1.getText();
       String choice=jComboBox1.getSelectedItem().toString();
       String a=jSpinner1.getValue().toString();
       int cost=Integer.parseInt(costm.getText());
       int cnt=Integer.parseInt(a);
        switch (choice) {
            case "KiloGrams":
                int mm=checkmainmaterials(name);
                if(mm==-1)
                         addnewmaterialkilos(name, cnt,cost);
                else updatekilos(name,cnt,cost,mm);
                         break;
            case "litres":
                         int ml=checkmainmaterials(name);
                if(ml==-1)
                         addnewmateriallitres(name, cnt,cost);
                else updatelitres(name,cnt,cost,ml);
                         break;
            case "blocks":
                         int mb=checkmainmaterials(name);
                if(mb==-1)
                         addnewmaterialblocks(name, cnt,cost);
                else updateblocks(name,cnt,cost,mb);
                         break;
            default:
                throw new AssertionError();
        }
    }//GEN-LAST:event_jButton4ActionPerformed


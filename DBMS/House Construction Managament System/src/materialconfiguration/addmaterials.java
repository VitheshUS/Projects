    public void materials()
    {
       try{
            Connection con=DBconnection.getconnnection();
            String query="select * from hcms.materials";
            PreparedStatement pr=con.prepareStatement(query);
            ResultSet rs=pr.executeQuery();
             tb1=(DefaultTableModel)jTable1.getModel();
            tb1.setRowCount(0);
            while(rs.next())
            {
                Object o[]={rs.getInt("mid"),rs.getString("name")};
                tb1.addRow(o);
            }
        } catch (SQLException ex) {
            java.util.logging.Logger.getLogger(adminengineers.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        }
    
    }

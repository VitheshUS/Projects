    public void updatekilos(String name,int count,int cost,int mid)
{
    int mcount=count;
    try{
        Connection con=DBconnection.getconnnection();
        String query="select quantity from hcms.kilogram where k_mid=?";
        PreparedStatement prt=con.prepareStatement(query);
        prt.setInt(1, mid);
        
       ResultSet rs=prt.executeQuery();
        if(rs.next()){
              mcount+=rs.getInt("quantity");
        } 
    }   catch (SQLException ex) {
            java.util.logging.Logger.getLogger(addmaterials.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        }
    System.out.println(mcount);
    try{
        Connection con=DBconnection.getconnnection();
        String query="update hcms.kilogram set quantity=?,cost=? where k_mid=?";
        PreparedStatement prt=con.prepareStatement(query);
        if(mcount!=0) prt.setInt(1, mcount);
        else  prt.setInt(1, count);
        prt.setInt(2, cost);
        prt.setInt(3, mid);
      int cc=prt.executeUpdate();
        if(cc>0){
              JOptionPane.showMessageDialog(this, "Succesfull");
        } 
        else JOptionPane.showMessageDialog(this, "Unsuccesfull");
    }   catch (SQLException ex) {
            java.util.logging.Logger.getLogger(addmaterials.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        } 
    materials();
}
        
